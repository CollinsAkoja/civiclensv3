"""Plain-language community issue report (Markdown), built from filtered data."""
from datetime import date
from typing import Optional

import pandas as pd

from core.analytics import by_location, counted, headline_metrics, top_keywords

LIMITATIONS = [
    "These figures come from community submissions. Unless a report is marked verified, it is a claim and not an independently confirmed fact.",
    "Categories, summaries and urgency levels marked as AI-generated are suggestions from a language model and can be wrong. They have not been calibrated as probabilities.",
    "Counts show how many reports were received, not how many problems exist. Areas with more internet access or awareness may report more.",
    "Possible duplicates are flagged for human review and may still be counted separately until a reviewer decides.",
]


def generate_report(df: pd.DataFrame, filters_text: str = "No filters applied",
                    pending_duplicate_flags: int = 0, today: Optional[date] = None) -> str:
    today = today or date.today()
    m = headline_metrics(df, pending_duplicate_flags)
    lines = [
        "# Community Issue Report", "",
        f"Generated by CivicLens AI on {today.isoformat()}.",
        f"Scope: {filters_text}.", "",
        "## Key figures", "",
        f"- Reports submitted: {m['submitted']}",
        f"- Awaiting human review: {m['awaiting_review']}",
        f"- Reviewed (approved or corrected): {m['reviewed']}",
        f"- Rejected: {m['rejected']}",
        f"- Verified unresolved: {m['verified_unresolved']}",
        f"- Verified resolved: {m['verified_resolved']}",
        f"- Possible duplicates awaiting review: {m['possible_duplicates_pending']}", "",
    ]

    if m["submitted"] == 0:
        lines += ["No reports match these filters.", ""]
    else:
        categories = counted(df, "effective_category")
        locations = by_location(df)
        lines += ["## Most reported concerns", ""]
        for row in categories.head(3).itertuples():
            lines.append(f"- {row.effective_category}: {row.reports} report(s)")
        if not locations.empty:
            lines += ["", "Areas with the most reports:", ""]
            for row in locations.head(3).itertuples():
                lines.append(f"- {row.location}: {row.reports} report(s)")
        keywords = top_keywords(df, 8)
        if keywords:
            lines += ["", "Frequent keywords (AI-extracted): " + ", ".join(f"{k} ({n})" for k, n in keywords)]
        lines.append("")

    lines += ["## Limitations", ""] + [f"- {item}" for item in LIMITATIONS] + [""]

    lines += ["## Suggested follow-up", ""]
    actions = []
    if m["awaiting_review"]:
        actions.append(f"Complete human review of the {m['awaiting_review']} report(s) still awaiting review.")
    if m["possible_duplicates_pending"]:
        actions.append("Resolve the flagged possible duplicates so counts are not inflated.")
    if m["submitted"]:
        top = counted(df, "effective_category").iloc[0]
        top_loc = by_location(df)
        place = f" in {top_loc.iloc[0]['location']}" if not top_loc.empty else ""
        actions.append(
            f"Verify the most frequently reported concern ({top['effective_category']}{place}) "
            "with local leaders or the responsible agency before acting on it."
        )
        if m["verified_resolved"] + m["verified_unresolved"] == 0:
            actions.append("Collect independent evidence (site visits, photos, agency records) so reports can be marked verified.")
    actions.append("Share this summary with the relevant community group or agency and record their response.")
    lines += [f"{i}. {a}" for i, a in enumerate(actions, 1)]
    return "\n".join(lines) + "\n"
